export function getCatalogVehiclesByBrand(brandSlug: string): CatalogVehicle[] {
  if (!brandSlug) return [];
  const normalized = brandSlug.toLowerCase().trim();
  return PAKISTAN_VEHICLE_CATALOG.filter(v => v.brandSlug.toLowerCase() === normalized);
}

export function getCatalogVehicleBySlug(brandSlug: string, modelSlug: string): CatalogVehicle | undefined {
  if (!brandSlug || !modelSlug) return undefined;
  const bNorm = brandSlug.toLowerCase().trim();
  const mNorm = modelSlug.toLowerCase().trim();
  return PAKISTAN_VEHICLE_CATALOG.find(
    v => v.brandSlug.toLowerCase() === bNorm && v.slug.toLowerCase() === mNorm
  );
}

export function getCatalogVehiclesByCategory(category: string): CatalogVehicle[] {
  if (!category) return [];
  const normalized = category.toLowerCase().trim();
  return PAKISTAN_VEHICLE_CATALOG.filter(v => v.category.toLowerCase() === normalized);
}
