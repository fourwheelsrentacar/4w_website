export function getCatalogVehiclesByBrand(brandSlug: string): CatalogVehicle[] {
  return PAKISTAN_VEHICLE_CATALOG.filter(v => v.brandSlug.toLowerCase() === brandSlug.toLowerCase());
}

export function getCatalogVehicleBySlug(brandSlug: string, modelSlug: string): CatalogVehicle | undefined {
  return PAKISTAN_VEHICLE_CATALOG.find(
    v => v.brandSlug.toLowerCase() === brandSlug.toLowerCase() && v.slug.toLowerCase() === modelSlug.toLowerCase()
  );
}

export function getCatalogVehiclesByCategory(category: string): CatalogVehicle[] {
  return PAKISTAN_VEHICLE_CATALOG.filter(v => v.category.toLowerCase() === category.toLowerCase());
}
