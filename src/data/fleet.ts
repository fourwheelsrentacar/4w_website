export type FleetImageType =
  | 'actual-fleet'
  | 'licensed-model'
  | 'automotive-api'
  | 'illustration'
  | 'fallback'
  | 'representative-photo'
  | 'model-illustration'
  | 'category-fallback';

export interface VehicleImageMetadata {
  type: 'actual-fleet' | 'licensed-model' | 'automotive-api' | 'illustration' | 'fallback';
  make: string;
  model: string;
  modelYear: number | string;
  generation: string;
  trim?: string;
  variant?: string;
  bodyStyle?: string;
  powertrain?: string;
  sourceProvider: 'local-fleet' | 'imagin' | 'carsxe' | 'evox' | 'local-licensed' | 'fallback';
  sourceUrl?: string;
  license?: string;
  licenseUrl?: string;
  verified: boolean;
  verifiedDate?: string;
  imageUrl: string;
  fallbackUrl?: string;
  reviewStatus: 'APPROVED' | 'REJECTED' | 'OWNER CONFIRMATION REQUIRED';
  label: string;
}

export interface ImageMetadata {
  hero: string;
  gallery?: string[];
  imageType: FleetImageType;
  sourceUrl?: string;
  author?: string;
  license?: string;
  licenseUrl?: string;
  vehicleGeneration?: string;
  dateChecked?: string;
}

